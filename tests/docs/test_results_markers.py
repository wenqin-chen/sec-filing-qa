"""Documentation freshness and honesty checks (the ``docs`` module's tests).

* ``RESULTS.md`` must equal what ``secqa report`` renders for the committed ``results/`` and
  ``configs/`` (the generation timestamp excluded), so a merged run that nobody re-rendered, or a
  hand-edited number, fails CI.
* The README block between ``<!-- results:start -->`` / ``<!-- results:end -->`` must equal
  ``RESULTS.md`` with every heading demoted one level (``sed 's/^#/##/' RESULTS.md``), so the
  README can never show numbers that the generator did not produce.
* The README keeps the section order the docs module promises, never contains a mock row, and
  ``docs/DATA.md`` carries the markers ``scripts/check_page_indexing.py`` writes into.
"""

from __future__ import annotations

import re
from pathlib import Path

from secqa.eval.report import render_results_md

REPO = Path(__file__).resolve().parents[2]
README = REPO / "README.md"
RESULTS_MD = REPO / "RESULTS.md"
DATA_MD = REPO / "docs" / "DATA.md"
CONFIGS_DIR = REPO / "configs"
RESULTS_DIR = REPO / "results"

RESULTS_START = "<!-- results:start -->"
RESULTS_END = "<!-- results:end -->"
PAGE_INDEXING_START = "<!-- page-indexing:start -->"
PAGE_INDEXING_END = "<!-- page-indexing:end -->"
STAMP_PREFIX = "Generated by `secqa report` on "
STAMP_PLACEHOLDER = "Generated by `secqa report` on <stamp>"
REGENERATE = (
    "regenerate with `uv run --no-sync secqa report results/ --out RESULTS.md`, then paste "
    "`sed 's/^#/##/' RESULTS.md` between the results markers in README.md"
)

README_SECTION_ORDER: tuple[str, ...] = (
    "## Why this exists",
    "## Live demo and status",
    "## Quickstart",
    "## Architecture",
    "## Results",
    "## Evaluation protocol (summary)",
    "## Non-goals (v0.1)",
    "## Limitations",
    "## Licence and attribution",
    "## Contributing",
)


def normalise_stamp(text: str) -> list[str]:
    """Lines of ``text`` with the generation timestamp line replaced by a fixed placeholder."""
    lines = text.rstrip("\n").splitlines()
    return [STAMP_PLACEHOLDER if line.startswith(STAMP_PREFIX) else line for line in lines]


def demote_headings(text: str) -> str:
    """``# H1`` -> ``## H2`` on every heading line (what the README embeds)."""
    return "\n".join(("#" + line) if line.startswith("#") else line for line in text.splitlines())


def block_between(text: str, start: str, end: str) -> str:
    """The text strictly between one ``start`` marker and one ``end`` marker."""
    assert text.count(start) == 1, f"expected exactly one {start!r}"
    assert text.count(end) == 1, f"expected exactly one {end!r}"
    first, last = text.index(start), text.index(end)
    assert first < last, "start marker must come before the end marker"
    return text[first + len(start) : last].strip("\n")


def test_results_md_matches_secqa_report() -> None:
    """The committed RESULTS.md is exactly what the generator renders today (stamp aside)."""
    rendered = render_results_md(RESULTS_DIR, CONFIGS_DIR)
    committed = RESULTS_MD.read_text(encoding="utf-8")
    assert committed.startswith("# Results\n")
    assert any(line.startswith(STAMP_PREFIX) for line in committed.splitlines())
    assert normalise_stamp(committed) == normalise_stamp(rendered), (
        f"RESULTS.md is stale; {REGENERATE}"
    )


def test_readme_block_equals_demoted_results_md() -> None:
    """The README results block is RESULTS.md with headings demoted one level."""
    readme = README.read_text(encoding="utf-8")
    block = block_between(readme, RESULTS_START, RESULTS_END)
    expected = demote_headings(RESULTS_MD.read_text(encoding="utf-8"))
    assert normalise_stamp(block) == normalise_stamp(expected), (
        f"README results block is stale; {REGENERATE}"
    )
    # The demoted document nests under the README's own "## Results" section.
    assert block.startswith("## Results\n")
    assert "\n# " not in "\n" + block, "the embedded block must not introduce a second H1"


def test_readme_block_never_shows_a_smoke_row() -> None:
    """Mock / scripted configs are footnoted, never tabulated (SPEC section 9)."""
    block = block_between(README.read_text(encoding="utf-8"), RESULTS_START, RESULTS_END)
    table_rows = [line for line in block.splitlines() if line.startswith("| `")]
    assert table_rows, "the results block should contain the configured rows"
    for row in table_rows:
        assert "_mock`" not in row and "scripted" not in row, row
    assert "`rag_mock`" in block and "`agent_mock`" in block  # listed as excluded by design


def test_pending_rows_are_pending_not_omitted() -> None:
    """Every non-smoke config under configs/ appears as a row; unrun rows say why."""
    block = block_between(README.read_text(encoding="utf-8"), RESULTS_START, RESULTS_END)
    config_names = {path.stem for path in CONFIGS_DIR.glob("*.yaml")}
    smoke = {name for name in config_names if name.endswith("_mock")}
    for name in config_names - smoke:
        assert f"| `{name}` |" in block, f"config {name} missing from the results block"
    # Only the two matrix tables carry a Status column; the breakdown and latency tables end in a
    # metric that is legitimately "—" for retrieval-only rows (no answering model, no faithfulness).
    for heading in ("### Retrieval", "### Question answering"):
        assert heading in block, heading
        section = block.split(heading, 1)[1].split("\n###", 1)[0]
        for line in section.splitlines():
            if line.startswith("| `") and line.endswith("| — |"):
                raise AssertionError(f"an unrun row must carry a status, not a dash: {line}")
    pending = re.findall(r"pending \(not run\): ([^|]+)\|", block)
    for reason in pending:
        assert reason.strip(), "a pending cell must state its reason"


def test_readme_section_order() -> None:
    """The README keeps the documented section order (docs module public interface)."""
    headings = [
        line.rstrip()
        for line in README.read_text(encoding="utf-8").splitlines()
        if line.startswith("## ")
    ]
    positions = [headings.index(section) for section in README_SECTION_ORDER]
    assert positions == sorted(positions), headings
    assert headings[0] == README_SECTION_ORDER[0]


def test_readme_states_the_licences_and_status_wording() -> None:
    """Licence notices and the honest deployment wording are present (SPEC section 9)."""
    readme = README.read_text(encoding="utf-8")
    for needle in (
        "CC-BY-NC-4.0",
        "MIT",
        "public domain",
        "deployment not yet verified",
        "pending (not run)",
    ):
        assert needle in readme, needle
    assert "deployed and smoke-tested on 20" not in readme, (
        "a verified-deployment claim needs a green smoke run in CI first"
    )


def test_data_md_carries_the_page_indexing_markers() -> None:
    """``scripts/check_page_indexing.py`` rewrites the block between these markers."""
    text = DATA_MD.read_text(encoding="utf-8")
    block = block_between(text, PAGE_INDEXING_START, PAGE_INDEXING_END)
    assert block, "the page-indexing block must not be empty"
    assert "evidence_page_num" in text and "page_num = evidence_page_num + 1" in text
